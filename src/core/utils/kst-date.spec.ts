import { endOfDayKstAfter } from './kst-date';

describe('endOfDayKstAfter', () => {
  const iso = (base: string, days: number) => endOfDayKstAfter(new Date(base), days).toISOString();

  it('퇴사일 + 3일 / + 15일 마감 (노션 명세 예시)', () => {
    // 2026-04-30 퇴사 → 자기평가 2026-05-03T23:59:59+09:00, 대표 검증 2026-05-15T23:59:59+09:00
    expect(iso('2026-04-30', 3)).toBe('2026-05-03T14:59:59.000Z');
    expect(iso('2026-04-30', 15)).toBe('2026-05-15T14:59:59.000Z');
  });

  it('대표 검증 완료 + 7일 의견 마감 (노션 명세 예시)', () => {
    // 2026-05-05T10:00:00+09:00 완료 → 2026-05-12T23:59:59+09:00
    expect(iso('2026-05-05T10:00:00+09:00', 7)).toBe('2026-05-12T14:59:59.000Z');
  });

  it('월말을 넘기면 다음 달로 넘어간다', () => {
    expect(iso('2026-01-30', 3)).toBe('2026-02-02T14:59:59.000Z');
    expect(iso('2026-04-30', 1)).toBe('2026-05-01T14:59:59.000Z');
  });

  it('연말을 넘기면 다음 해로 넘어간다', () => {
    expect(iso('2026-12-30', 3)).toBe('2027-01-02T14:59:59.000Z');
    expect(iso('2026-12-31', 15)).toBe('2027-01-15T14:59:59.000Z');
  });

  it('2월 윤년·평년을 구분한다', () => {
    expect(iso('2028-02-27', 3)).toBe('2028-03-01T14:59:59.000Z'); // 2028 윤년: 2/29 존재
    expect(iso('2026-02-27', 3)).toBe('2026-03-02T14:59:59.000Z'); // 2026 평년
  });

  it('UTC로는 전날이어도 KST 날짜를 기준으로 계산한다', () => {
    // 2026-05-04T15:30Z = KST 5/5 00:30 → KST 5/5 당일 마감
    expect(iso('2026-05-04T15:30:00Z', 0)).toBe('2026-05-05T14:59:59.000Z');
    // 2026-05-04T14:59Z = KST 5/4 23:59 → KST 5/4 당일 마감
    expect(iso('2026-05-04T14:59:00Z', 0)).toBe('2026-05-04T14:59:59.000Z');
  });
});
